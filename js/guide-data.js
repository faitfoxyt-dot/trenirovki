const norm = (s) => String(s ?? '').toLowerCase().replace(/ё/g, 'е').replace(/[()]/g, ' ');

// Карточка справочника для упражнения из каталога, или null, если картинки ещё нет.
export function guideFor(name) {
  const n = norm(name);
  return GUIDE.find((g) => g.match.test(n)) ?? null;
}
