// Справочник упражнений: позы для человечка, шаги и частые ошибки.
// Упражнение из каталога находится по названию (match), поэтому id в базе и демо не важны.
// Кадры (frames) — позы, между которыми человечек двигается; cap — подпись к кадру.

import { L } from './figure.js';

const Y = { hand: 114.8, ankle: 115.7, lie: 111.8 }; // кисть, щиколотка и корпус на полу

// Прямое тело от щиколотки (или колена при lower = бедро): плечо на высоте shY,
// таз и наклон считаются так, чтобы ноги и корпус легли одной линией.
function plank(from, shY, lower = L.th + L.sh) {
  const len = L.torso + lower - 0.4;
  const dy = shY - from[1];
  const sh = [from[0] + Math.sqrt(len * len - dy * dy), shY];
  const k = L.torso / len;
  const hip = [sh[0] + (from[0] - sh[0]) * k, sh[1] + (from[1] - sh[1]) * k];
  const t = (Math.atan2(sh[0] - hip[0], -(sh[1] - hip[1])) * 180) / Math.PI;
  return { hip, t };
}
// Тот же плечевой пояс, но таз опущен (или поднят) — для картинки ошибки.
function shift(p, dy) {
  const sh = [p.hip[0] + Math.sin((p.t * Math.PI) / 180) * L.torso, p.hip[1] - Math.cos((p.t * Math.PI) / 180) * L.torso];
  const hip = [p.hip[0], p.hip[1] + dy];
  return { ...p, hip, t: (Math.atan2(sh[0] - hip[0], -(sh[1] - hip[1])) * 180) / Math.PI };
}

